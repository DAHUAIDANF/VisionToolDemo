              也可以点工具条「坐标系自检」：它会报出 物理分辨率 / 本进程坐标空间 /
              抓屏尺寸，并**实测**一次“屏幕上的标记在抓屏图里落在哪”，直接给出偏差；
              自检说“对不齐”就把报告发我。100% 缩放下换算比恒为 1，行为与以前一致。
