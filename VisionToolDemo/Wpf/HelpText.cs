              两种都没有的匹配节点，点“运行”会被拦住并指出是哪个节点。
            • 运行：“运行”跑一轮整张图；“停止”中断；“循环运行…”把当前节点图按设定的
              轮数与间隔反复执行（可选“一轮里有动作被跳过就停”）。开始前会先校验节点图，
              并提醒“图里没有鼠标点击/键盘输入节点”这类跑完什么也没发生的情况。
            • 真实执行前建议点一次「测试鼠标定位」：它会把光标移到两个点再还原，
              几秒钟就能确认这台机器/这个会话允不允许程序控制光标。
              程序优先用 SetCursorPos；被系统拒绝时自动改用注入式移动（SendInput 绝对模式）；
              两条都不行才会报错，并给出 Win32 错误码与常见原因。
              常见失败原因：目标程序以管理员权限运行而本程序不是（可让本程序也以管理员运行）、
              屏幕已锁定或停在 UAC 安全桌面、光标被别的程序限制在某个矩形里（游戏/全屏程序）、
              远程桌面会话已断开、虚拟机没有鼠标设备。
              另外：SetCursorPos 报告成功时也会读回光标核对 —— “以为点了其实没动”比报错更危险。
              真实执行前程序还会自动做一次自检（在“本程序窗口隐藏”的状态下试移动光标），
              不允许就直接放弃本次运行并说明原因，不会跑到一半才失败。
            • 自检会分别测“窗口可见 / 窗口隐藏 / 窗口移出屏幕”三种状态；程序在真实执行前
              还会自动挑一种可行方式：优先“隐藏窗口”，如果隐藏后无法控制光标，
              就自动改成“把本窗口移出屏幕”（前台仍是我们自己，注入不会被拦，
